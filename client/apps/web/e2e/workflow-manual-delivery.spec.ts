import type { EnterpriseWorkflowExecution } from '@clawee/protocol';
import { test, expect } from './fixtures/workflow-runtime.js';
import { workflowTemplate } from './support/workflow-gateway.js';

test('节点多轮对话、人工修改和刷新恢复后，仅人工点击才提交', async ({ page, runtime, workflowGateway }, testInfo) => {
  runtime.configureInvocations([{ message: '# AI 第一稿\n\n待修改的内容。' }, { message: '# AI 第二稿\n\n补充后的内容。' }]);
  const started = await runtime.api<{ data: { task_id: string } }>('POST', `/enterprise/workflow-templates/${workflowTemplate.id}/instances`, { initialInput: { text: '需要人工定稿的报告' }, idempotencyKey: 'manual-delivery-e2e' });
  const taskId = started.data.task_id;
  await runtime.openApp(page);
  if (testInfo.project.name === 'chromium-mobile') await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await page.getByRole('button', { name: '工作流', exact: true }).click();
  await page.getByRole('button', { name: /Agent · 整理初始输入/ }).click();
  await page.getByRole('button', { name: '打开执行会话', exact: true }).click();
  await expect(page.getByRole('region', { name: '所属流程任务' })).toContainText(workflowTemplate.name);
  expect(runtime.readInvocationCount()).toBe(0);
  const firstInput = page.getByRole('textbox', { name: '任务要求', exact: true });
  await expect(firstInput).toHaveValue('需要人工定稿的报告');
  await firstInput.press('Enter');
  const panel = page.getByRole('region', { name: '节点交付结果' });
  await expect(panel.getByText('待人工确认', { exact: true })).toBeVisible();
  expect(workflowGateway.completionRequests).toHaveLength(0);
  expect(workflowGateway.instances[0]!.tasks[0]!.status).toBe('pending');
  await page.getByRole('button', { name: '返回流程任务', exact: true }).click();
  await expect(page.getByRole('navigation', { name: '节点进度' }).getByText('待人工确认', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '继续处理节点', exact: true }).click();
  await expect(panel.getByText('待人工确认', { exact: true })).toBeVisible();
  expect(runtime.readInvocationCount()).toBe(1);
  await panel.getByRole('button', { name: '编辑交付结果' }).click();
  await panel.getByRole('textbox', { name: '交付结果正文' }).fill('# 人工定稿\n\n保留这一份，不被 AI 覆盖。');
  await panel.getByRole('button', { name: '保存修改' }).click();
  await expect(panel.getByText('已保存', { exact: true })).toBeVisible();
  const input = page.getByRole('textbox', { name: '输入任务', exact: true });
  await input.fill('补充一些背景，但不要替换我的定稿');
  await input.press('Enter');
  await expect.poll(() => runtime.readInvocationCount()).toBe(2);
  await expect.poll(async () => (await runtime.api<EnterpriseWorkflowExecution>('GET', `/enterprise/workflow-tasks/${taskId}/execution`)).status).toBe('awaiting_confirmation');
  const state = await runtime.api<EnterpriseWorkflowExecution>('GET', `/enterprise/workflow-tasks/${taskId}/execution`);
  expect(state.delivery!.text).toContain('人工定稿');
  expect(state.delivery!.latestText).toContain('AI 第二稿');
  expect(workflowGateway.completionRequests).toHaveLength(0);
  await page.reload();
  await expect(page.getByRole('region', { name: '所属流程任务' })).toContainText(workflowTemplate.name);
  await panel.getByText('交付结果 · 已人工修改', { exact: true }).click();
  await expect(panel.getByRole('heading', { name: '人工定稿' })).toBeVisible();
  await panel.getByRole('button', { name: '编辑交付结果' }).click();
  await expect(panel.getByRole('textbox')).toHaveValue('# 人工定稿\n\n保留这一份，不被 AI 覆盖。');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('manual-delivery-editor.png') });
  await panel.getByRole('button', { name: '取消', exact: true }).click();
  await panel.getByRole('button', { name: '完成节点并上传结果', exact: true }).click();
  await expect(page.getByText('节点已完成', { exact: true })).toBeVisible();
  expect(workflowGateway.completionRequests).toHaveLength(1);
  expect(workflowGateway.completionRequests[0]!.output).toEqual({ text: '# 人工定稿\n\n保留这一份，不被 AI 覆盖。' });
  await page.screenshot({ path: testInfo.outputPath('manual-delivery-completed.png') });
});
